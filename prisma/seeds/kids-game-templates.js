export async function seedKidsGameTemplates(client = prisma) {
  let count = 0;
  for (const t of KIDS_TEMPLATES_SEED_DATA) {
    await client.kidsGameTemplate.upsert({
      where: { id: t.id },
      update: t,
      create: t,
    });
    count++;
  }
  console.log(`✓ ${count} Kids Game Templates seeded`);
  return count;
}

// Allow standalone execution
if (process.argv[1]?.endsWith('kids-game-templates.js')) {
  seedKidsGameTemplates()
    .catch((err) => {
      console.error('Failed to seed kids game templates:', err);
      process.exit(1);
    })
    .finally(() => prisma.$disconnect());
}
