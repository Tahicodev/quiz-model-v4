/**
 * src/backend/services/exerciseRenderer.js
 *
 * Renders an AI-generated lesson EXERCISE (see AIService.generateLessonExercise)
 * to Word or PDF. An exercise is a situation-problem, not a question: the
 * document presents the scenario, the data the student is given and the tasks,
 * then a separate CORRECTION page with the worked solution.
 *
 * The layout deliberately mirrors prepSheetRenderer's visual language (same
 * accent colours, Georgia body, page chrome) but stays portrait-only: there is
 * no wide grid to place, so a single A4 column is enough. Word-corruption
 * guards are the same: cell text is stripped of C0 control characters and
 * bullets are emitted as plain prefixed paragraphs (no numbering definition
 * that could serialize an invalid <w:ilvl/>).
 */

