const labelsFor = (language) => {
	const key = String(language || '').toLowerCase();
	return key.startsWith('english') ? LABELS.English : LABELS.French;
};

const difficultyLabel = (value, L) => {
	const raw = String(value || '').toLowerCase();
	if (L === LABELS.English) return raw === 'easy' ? 'Easy' : raw === 'hard' ? 'Hard' : 'Medium';
	return raw === 'easy' ? 'Facile' : raw === 'hard' ? 'Difficile' : 'Moyen';
};

const taskList = (exercise) => {
	const tasks = Array.isArray(exercise?.tasks) ? exercise.tasks : [];
	return tasks
		.map((task, i) => ({
			index: i + 1,
			prompt: asText(task?.prompt).trim(),
			points: Number.isFinite(Number(task?.points)) ? Math.max(0, Math.round(Number(task.points))) : 0,
		}))
		.filter((task) => task.prompt);
};

// ── DOCX ────────────────────────────────────────────────────────────────────

const DOCX_BORDER = { style: BorderStyle.SINGLE, size: 4, color: THEME.border };
const DOCX_BORDERS = {
	top: DOCX_BORDER, bottom: DOCX_BORDER, left: DOCX_BORDER, right: DOCX_BORDER,
	insideHorizontal: DOCX_BORDER, insideVertical: DOCX_BORDER,
};
const DOCX_CELL_MARGINS = { top: 60, bottom: 60, left: 90, right: 90 };
const PAGE = { width: 11906, height: 16838, margin: 850 };
const CONTENT_WIDTH = PAGE.width - PAGE.margin * 2;

function docxRun(text, options = {}) {
	return new TextRun({
		text: stripInvalidXmlChars(asText(text)),
		font: options.font || THEME.font,
		size: options.size ?? 22,
		bold: options.bold,
		italics: options.italics,
		color: options.color || THEME.ink,
	});
}

function docxHeading(text, level) {
	return new Paragraph({
		heading: level,
		spacing: { before: 240, after: 120 },
		keepNext: true,
		children: [docxRun(text, { bold: true, size: level === HeadingLevel.HEADING_1 ? 30 : 26, color: THEME.accent.slice(1) })],
	});
}

function docxParagraph(text, options = {}) {
	return new Paragraph({
		spacing: { after: 100, line: 276 },
		alignment: options.alignment || AlignmentType.LEFT,
		children: [docxRun(text, options)],
	});
}

function docxBullet(text) {
	return new Paragraph({
		spacing: { after: 60, line: 264 },
		indent: { left: 320, hanging: 180 },
		children: [docxRun('•  ', { bold: true, color: THEME.accent.slice(1) }), docxRun(text)],
	});
}

function docxNumbered(index, text, points, L) {
	const children = [docxRun(`${index}.  `, { bold: true, color: THEME.accent.slice(1) }), docxRun(text)];
	if (points > 0) children.push(docxRun(`   (${points} ${L.points.toLowerCase()})`, { italics: true, size: 20, color: THEME.muted }));
	return new Paragraph({ spacing: { after: 80, line: 276 }, indent: { left: 320, hanging: 320 }, children });
}

function docxInfoCell(text, options = {}) {
	return new TableCell({
		width: { size: options.width, type: WidthType.DXA },
		columnSpan: options.span,
		shading: options.fill ? { type: ShadingType.CLEAR, fill: options.fill, color: 'auto' } : undefined,
		margins: DOCX_CELL_MARGINS,
		verticalAlign: 'center',
		children: [new Paragraph({
			spacing: { after: 0 },
			children: [docxRun(text, { bold: options.bold, size: options.size ?? 20, color: options.color || THEME.ink })],
		})],
	});
}

function docxHeaderRow(labels, widths) {
	return new TableRow({
		tableHeader: true,
		children: labels.map((label, i) => new TableCell({
			width: { size: widths[i], type: WidthType.DXA },
			shading: { type: ShadingType.CLEAR, fill: THEME.accent.slice(1), color: 'auto' },
			margins: DOCX_CELL_MARGINS,
			children: [new Paragraph({
				spacing: { after: 0 },
				children: [docxRun(label, { bold: true, size: 20, color: 'FFFFFF' })],
			})],
		})),
	});
}

function docxTasksTable(tasks, L) {
	const widths = [Math.round(CONTENT_WIDTH * 0.08), Math.round(CONTENT_WIDTH * 0.78)];
	widths.push(CONTENT_WIDTH - widths[0] - widths[1]);
	return new Table({
		width: { size: CONTENT_WIDTH, type: WidthType.DXA },
		columnWidths: widths,
		layout: TableLayoutType.FIXED,
		borders: DOCX_BORDERS,
		rows: [
			docxHeaderRow(['#', L.taskColumn, L.points], widths),
			...tasks.map((task) => new TableRow({
				cantSplit: true,
				children: [
					docxInfoCell(String(task.index), { width: widths[0], bold: true, color: THEME.accent.slice(1) }),
					docxInfoCell(task.prompt, { width: widths[1] }),
					docxInfoCell(task.points ? String(task.points) : '—', { width: widths[2], bold: true }),
				],
			})),
		],
	});
}

async function renderExerciseDocx(exercise, headerInfo, L) {
	const tasks = taskList(exercise);
	const givenData = toList(exercise?.givenData);
	const solutionSteps = toList(exercise?.solutionSteps);
	const competencies = toList(exercise?.keyCompetencies);
	const title = asText(exercise?.title) || asText(headerInfo.lessonTitle) || L.docTitle;

	const runningHeader = new Header({
		children: [new Paragraph({
			border: { bottom: { style: BorderStyle.SINGLE, size: 4, color: THEME.accent.slice(1), space: 4 } },
			children: [docxRun(
				[asText(headerInfo.teacherName), asText(headerInfo.academicYear)].filter(Boolean).join('  ·  ') || asText(headerInfo.institution),
				{ bold: true, size: 16, color: THEME.accent.slice(1) },
			)],
		})],
	});
	const footer = new Footer({
		children: [new Paragraph({
			tabStops: [{ type: TabStopType.RIGHT, position: CONTENT_WIDTH }],
			border: { top: { style: BorderStyle.SINGLE, size: 4, color: 'D2D8E0', space: 4 } },
			children: [
				docxRun([asText(headerInfo.courseName), asText(headerInfo.lessonTitle)].filter(Boolean).join(' — ') || title, { size: 16, color: THEME.muted }),
				new TextRun({ children: [new Tab(), `${L.page} `], size: 16, color: THEME.muted, font: THEME.font }),
				new TextRun({ children: [PageNumber.CURRENT], size: 16, color: THEME.muted, font: THEME.font }),
				new TextRun({ text: ' / ', size: 16, color: THEME.muted, font: THEME.font }),
				new TextRun({ children: [PageNumber.TOTAL_PAGES], size: 16, color: THEME.muted, font: THEME.font }),
			],
		})],
	});

	const infoPairs = [
		[L.subject, headerInfo.subject || headerInfo.courseName],
		[L.level, headerInfo.level],
		[L.module, headerInfo.module || headerInfo.categoryPath],
		[L.lesson, headerInfo.lessonTitle],
		[L.teacher, headerInfo.teacherName],
		[L.date, headerInfo.date],
		[L.difficulty, difficultyLabel(exercise?.difficulty, L)],
		[L.academicYear, headerInfo.academicYear],
	].filter(([, value]) => asText(value).trim());

	const infoWidths = (() => {
		const first = Math.round(CONTENT_WIDTH * 0.24);
		const second = Math.round(CONTENT_WIDTH * 0.26);
		const third = Math.round(CONTENT_WIDTH * 0.24);
		return [first, second, third, CONTENT_WIDTH - first - second - third];
	})();
	const infoTable = infoPairs.length
		? new Table({
			width: { size: CONTENT_WIDTH, type: WidthType.DXA },
			columnWidths: infoWidths,
			layout: TableLayoutType.FIXED,
			borders: DOCX_BORDERS,
			rows: (() => {
				const rows = [];
				for (let i = 0; i < infoPairs.length; i += 2) {
					const pair = infoPairs[i];
					const next = infoPairs[i + 1];
					rows.push(new TableRow({
						cantSplit: true,
						children: [
							docxInfoCell(pair[0], { width: infoWidths[0], bold: true, size: 18, fill: THEME.accentSoft.slice(1) }),
							docxInfoCell(pair[1], { width: infoWidths[1], size: 18 }),
							docxInfoCell(next ? next[0] : '', { width: infoWidths[2], bold: true, size: 18, fill: THEME.accentSoft.slice(1) }),
							docxInfoCell(next ? next[1] : '', { width: infoWidths[3], size: 18 }),
						],
					}));
				}
				return rows;
			})(),
		})
		: null;

	const studentChildren = [
		new Paragraph({
			alignment: AlignmentType.CENTER,
			spacing: { after: 60 },
			children: [docxRun(asText(headerInfo.institution || headerInfo.schoolName || headerInfo.ministry) || ' ', { bold: true, size: 24, color: THEME.accent.slice(1) })],
		}),
		new Paragraph({
			alignment: AlignmentType.CENTER,
			spacing: { after: 240 },
			keepNext: true,
			children: [docxRun(`${L.docTitle} — ${title}`, { bold: true, size: 32 })],
		}),
	];
	if (infoTable) studentChildren.push(infoTable, new Paragraph({ spacing: { after: 120 }, children: [] }));

	studentChildren.push(docxHeading(L.situation, HeadingLevel.HEADING_1));
	studentChildren.push(docxParagraph(asText(exercise?.situation) || '—'));

	if (givenData.length) {
		studentChildren.push(docxHeading(L.givenData, HeadingLevel.HEADING_2));
		studentChildren.push(...givenData.map(docxBullet));
	}

	if (tasks.length) {
		studentChildren.push(docxHeading(L.tasks, HeadingLevel.HEADING_2));
		studentChildren.push(docxTasksTable(tasks, L));
	}

	const correctionChildren = [
		new Paragraph({ pageBreakBefore: true, children: [] }),
		docxHeading(`${L.correction} — ${title}`, HeadingLevel.HEADING_1),
		docxParagraph(L.correctionNote, { italics: true, size: 20, color: THEME.muted }),
	];
	if (solutionSteps.length) {
		correctionChildren.push(docxHeading(L.solutionSteps, HeadingLevel.HEADING_2));
		correctionChildren.push(...solutionSteps.map((step, i) => docxNumbered(i + 1, step, 0, L)));
	}
	if (asText(exercise?.finalAnswer).trim()) {
		correctionChildren.push(docxHeading(L.finalAnswer, HeadingLevel.HEADING_2));
		correctionChildren.push(new Paragraph({
			spacing: { after: 120 },
			shading: { type: ShadingType.CLEAR, fill: THEME.accentSoft.slice(1), color: 'auto' },
			border: { left: { style: BorderStyle.SINGLE, size: 12, color: THEME.accent.slice(1), space: 8 } },
			children: [docxRun(asText(exercise.finalAnswer), { bold: true })],
		}));
	}
	if (competencies.length) {
		correctionChildren.push(docxHeading(L.competencies, HeadingLevel.HEADING_2));
		correctionChildren.push(...competencies.map(docxBullet));
	}
	correctionChildren.push(new Paragraph({
		spacing: { before: 240 },
		children: [docxRun(L.generatedBy, { italics: true, size: 18, color: THEME.muted })],
	}));

	const doc = new Document({
		styles: {
			default: { document: { run: { font: THEME.font, size: 22, color: THEME.ink } } },
			paragraphStyles: [
				{ id: 'Normal', name: 'Normal', run: { font: THEME.font, size: 22, color: THEME.ink }, paragraph: { spacing: { after: 100, line: 276 } } },
			],
		},
		sections: [{
			properties: {
				page: {
					size: { width: PAGE.width, height: PAGE.height },
					margin: { top: PAGE.margin, right: PAGE.margin, bottom: PAGE.margin, left: PAGE.margin },
				},
				titlePage: true,
			},
			headers: { default: runningHeader, first: new Header({ children: [new Paragraph({ children: [] })] }) },
			footers: { default: footer, first: footer },
			children: [...studentChildren, ...correctionChildren],
		}],
	});
	return Packer.toBuffer(doc);
}

// ── PDF ─────────────────────────────────────────────────────────────────────

function pdfBuffer(exercise, headerInfo, L) {
	return new Promise((resolve, reject) => {
		const doc = new PDFDocument({
			size: 'A4',
			layout: 'portrait',
			margins: { top: 52, right: 54, bottom: 56, left: 54 },
			bufferPages: true,
			info: {
				Title: `${L.docTitle} — ${exercise?.title || headerInfo.lessonTitle || ''}`,
				Author: headerInfo.teacherName || 'Quiz App',
				Subject: headerInfo.subject || headerInfo.lessonTitle || '',
				Creator: 'Quiz App — lesson exercise generator',
			},
		});
		const chunks = [];
		doc.on('data', (c) => chunks.push(c));
		doc.on('end', () => resolve(Buffer.concat(chunks)));
		doc.on('error', reject);

		const ACCENT = THEME.accent;
		const INK = '#273449';
		const MUTED = '#8A97A8';
		const FONT = 'Helvetica';
		const sanitize = (value) => stripInvalidXmlChars(asText(value).replace(/[^\x20-\x7E\u00A0-\uFFFF\t]/g, ''));

		const left = () => doc.page.margins.left;
		const width = () => doc.page.width - doc.page.margins.left - doc.page.margins.right;
		const bottomY = () => doc.page.height - doc.page.margins.bottom;
		const ensureRoom = (needed) => {
			if (doc.y + needed > bottomY() - 8) doc.addPage();
		};

		const h1 = (text) => {
			ensureRoom(52);
			doc.moveDown(0.6);
			doc.font(`${FONT}-Bold`).fontSize(15).fillColor(ACCENT).text(sanitize(text), left(), doc.y, { width: width() });
			doc.moveDown(0.25);
			doc.moveTo(left(), doc.y).lineTo(left() + width(), doc.y).lineWidth(0.6).strokeColor('#d2d8e0').stroke();
			doc.moveDown(0.5);
		};
		const h2 = (text) => {
			ensureRoom(40);
			doc.moveDown(0.5);
			doc.font(`${FONT}-Bold`).fontSize(11.5).fillColor(ACCENT).text(sanitize(text), left(), doc.y, { width: width() });
			doc.moveDown(0.25);
		};
		const para = (text, options = {}) => {
			const body = sanitize(text);
			if (!body) return;
			const size = options.size || 10.5;
			const h = doc.font(options.italic ? `${FONT}-Oblique` : FONT).fontSize(size).heightOfString(body, { width: width() });
			ensureRoom(h + 8);
			doc.font(options.italic ? `${FONT}-Oblique` : FONT).fontSize(size)
				.fillColor(options.color || INK)
				.text(body, left(), doc.y, { width: width(), align: options.align || 'left', lineGap: 2 });
			doc.moveDown(0.35);
		};
		const bullet = (text) => {
			const size = 10.5;
			const body = sanitize(text);
			if (!body) return;
			const indent = 14;
			const h = doc.font(FONT).fontSize(size).heightOfString(body, { width: width() - indent });
			ensureRoom(h + 6);
			const y = doc.y;
			doc.font(`${FONT}-Bold`).fontSize(size).fillColor(ACCENT).text('•', left(), y, { width: indent });
			doc.font(FONT).fontSize(size).fillColor(INK).text(body, left() + indent, y, { width: width() - indent, lineGap: 2 });
			doc.y = y + Math.max(h, size) + 2;
		};
		const numbered = (n, text) => {
			const size = 10.5;
			const body = sanitize(text);
			if (!body) return;
			const indent = 20;
			const h = doc.font(FONT).fontSize(size).heightOfString(body, { width: width() - indent });
			ensureRoom(h + 6);
			const y = doc.y;
			doc.font(`${FONT}-Bold`).fontSize(size).fillColor(ACCENT).text(`${n}.`, left(), y, { width: indent });
			doc.font(FONT).fontSize(size).fillColor(INK).text(body, left() + indent, y, { width: width() - indent, lineGap: 2 });
			doc.y = y + Math.max(h, size) + 3;
		};
		const infoLine = (label, value) => {
			const text = sanitize(value);
			if (!text) return;
			ensureRoom(18);
			const y = doc.y;
			const labelWidth = Math.min(120, width() * 0.32);
			doc.font(`${FONT}-Bold`).fontSize(9).fillColor(MUTED).text(sanitize(label).toUpperCase(), left(), y, { width: labelWidth });
			doc.font(FONT).fontSize(10).fillColor(INK).text(text, left() + labelWidth, y, { width: width() - labelWidth });
			doc.y = Math.max(doc.y, y + 14);
		};

		const tasks = taskList(exercise);
		const givenData = toList(exercise?.givenData);
		const solutionSteps = toList(exercise?.solutionSteps);
		const competencies = toList(exercise?.keyCompetencies);
		const title = asText(exercise?.title) || asText(headerInfo.lessonTitle) || L.docTitle;

		// Cover block
		doc.font(`${FONT}-Bold`).fontSize(12).fillColor(ACCENT)
			.text(sanitize(headerInfo.institution || headerInfo.schoolName || headerInfo.ministry) || ' ', left(), doc.y, { width: width(), align: 'center' });
		doc.moveDown(0.8);
		doc.font(`${FONT}-Bold`).fontSize(18).fillColor(INK)
			.text(`${sanitize(L.docTitle)} — ${sanitize(title)}`, left(), doc.y, { width: width(), align: 'center' });
		doc.moveDown(1);
		[
			[L.subject, headerInfo.subject || headerInfo.courseName],
			[L.level, headerInfo.level],
			[L.module, headerInfo.module || headerInfo.categoryPath],
			[L.lesson, headerInfo.lessonTitle],
			[L.teacher, headerInfo.teacherName],
			[L.date, headerInfo.date],
			[L.difficulty, difficultyLabel(exercise?.difficulty, L)],
			[L.academicYear, headerInfo.academicYear],
		].forEach(([label, value]) => infoLine(label, value));

		h1(L.situation);
		para(exercise?.situation || '—');

		if (givenData.length) {
			h2(L.givenData);
			givenData.forEach(bullet);
		}
		if (tasks.length) {
			h2(L.tasks);
			tasks.forEach((task) => numbered(task.index, task.points ? `${task.prompt}  (${task.points} ${L.points.toLowerCase()})` : task.prompt));
		}

		// Correction page
		doc.addPage();
		h1(`${L.correction} — ${title}`);
		para(L.correctionNote, { italic: true, size: 9, color: MUTED });
		if (solutionSteps.length) {
			h2(L.solutionSteps);
			solutionSteps.forEach((step, i) => numbered(i + 1, step));
		}
		if (asText(exercise?.finalAnswer).trim()) {
			h2(L.finalAnswer);
			const answer = sanitize(exercise.finalAnswer);
			const boxWidth = width() - 20;
			const boxHeight = doc.font(`${FONT}-Bold`).fontSize(11).heightOfString(answer, { width: boxWidth, lineGap: 2 }) + 16;
			ensureRoom(boxHeight + 12);
			const y = doc.y;
			doc.save();
			doc.roundedRect(left(), y, width(), boxHeight, 4).fill(THEME.accentSoft);
			doc.restore();
			doc.font(`${FONT}-Bold`).fontSize(11).fillColor(ACCENT)
				.text(answer, left() + 10, y + 8, { width: boxWidth, lineGap: 2 });
			doc.y = y + boxHeight + 6;
		}
		if (competencies.length) {
			h2(L.competencies);
			competencies.forEach(bullet);
		}
		para(L.generatedBy, { italic: true, size: 8.5, color: MUTED });

		// Running chrome: header from page 2, footer with page numbers everywhere.
		const range = doc.bufferedPageRange();
		const headLeft = sanitize([asText(headerInfo.teacherName), asText(headerInfo.academicYear)].filter(Boolean).join('  ·  '));
		const footLeft = sanitize([asText(headerInfo.courseName), asText(headerInfo.lessonTitle)].filter(Boolean).join(' — ') || title);
		for (let p = 0; p < range.count; p += 1) {
			doc.switchToPage(p);
			const mL = doc.page.margins.left;
			const pageW = doc.page.width - doc.page.margins.left - doc.page.margins.right;
			if (p > 0 && headLeft) {
				doc.font(`${FONT}-Bold`).fontSize(8).fillColor(ACCENT)
					.text(headLeft, mL, 26, { width: pageW, lineBreak: false });
				doc.moveTo(mL, 37).lineTo(mL + pageW, 37).lineWidth(0.5).strokeColor(ACCENT).stroke();
			}
			const savedBottom = doc.page.margins.bottom;
			doc.page.margins.bottom = 0;
			const fy = doc.page.height - savedBottom + 14;
			doc.moveTo(mL, fy - 7).lineTo(mL + pageW, fy - 7).lineWidth(0.5).strokeColor('#d2d8e0').stroke();
			doc.font(FONT).fontSize(8).fillColor(MUTED)
				.text(footLeft, mL, fy, { width: pageW * 0.75, lineBreak: false });
			doc.text(`${L.page} ${p + 1} / ${range.count}`, mL + pageW * 0.75, fy, { width: pageW * 0.25, align: 'right', lineBreak: false });
			doc.page.margins.bottom = savedBottom;
		}
		doc.end();
	});
}

// ── Entry point ─────────────────────────────────────────────────────────────

export async function renderExercise(exercise, headerInfo = {}, format = 'docx') {
	if (!exercise || (!asText(exercise.situation).trim() && !taskList(exercise).length)) {
		throw new Error('Exercise has no situation or tasks to render');
	}
	const L = labelsFor(exercise.language);
	if (format === 'pdf') {
		return { buffer: await pdfBuffer(exercise, headerInfo, L), mime: 'application/pdf', extension: 'pdf' };
	}
	if (format !== 'docx') throw new Error(`Unsupported exercise format: ${format}`);
	return {
		buffer: await renderExerciseDocx(exercise, headerInfo, L),
		mime: 'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
		extension: 'docx',
	};
}