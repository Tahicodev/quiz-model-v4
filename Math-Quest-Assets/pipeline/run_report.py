"""Stage 3: write pipeline/processing-report.md from stage metrics."""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from config import STAGE

with open(os.path.join(STAGE, "metrics.json"), encoding="utf-8") as f:
    metrics = json.load(f)
with open(os.path.join(STAGE, "validation.json"), encoding="utf-8") as f:
    validation = json.load(f)

CAT_FALLBACK = {
    "mq-dino-idle": "characters", "mq-dino-celebrate": "characters", "mq-dino-thinking": "characters",
    "mq-dino-surprised": "characters", "mq-dino-encourage": "characters",
    "mq-jungle-home": "backgrounds", "mq-adventure-trail": "backgrounds",
    "mq-treasure-clearing": "backgrounds", "mq-ancient-temple": "backgrounds",
    "mq-sunset-jungle": "backgrounds",
    "mq-chest-closed": "props", "mq-chest-open": "props", "mq-chest-open-glow": "props",
    "mq-signpost": "props", "mq-gate": "props", "mq-crystal": "props", "mq-pedestal": "props",
    "mq-grass-tile": "terrain", "mq-path-tile": "terrain", "mq-floating-platform": "terrain",
    "mq-coin": "rewards", "mq-star": "rewards", "mq-trophy": "rewards",
    "mq-confetti": "effects", "mq-jungle-decorations": "decorations", "math-quest-icon": "icons",
}
def cat_of(pid):
    if pid in CAT_FALLBACK:
        return CAT_FALLBACK[pid]
    if pid.startswith("mq-decor-"):
        return "decorations"
    if pid.startswith("mq-level-"):
        return "thumbnails"
    raise KeyError(pid)

rows = []
for pid, rec in metrics.items():
    out0 = rec["outputs"][0]
    fmt = out0["format"]
    # metrics relpaths may predate the relocation to public/kids/assets
    out_rel = (out0["relpath"]
               .replace("public/assets/games/math-quest/", "")
               .replace("public/kids/assets/math-quest/", ""))
    ops = " + ".join(rec["operations"])
    extra = ""
    mm = out0.get("matting")
    if mm:
        extra = (f"matte(tol={mm['tol']}, min>={mm['neutral_min']}, span<={mm['neutral_span']}), "
                 f"{mm['bg_removed_pct']}% bg removed, junk={mm['loose_junk_px']}px")
    if "original_seam" in out0:
        s0, s1 = out0["original_seam"], out0["final_seam"]
        extra = f"seam original: {s0['left_right_mean']}/{s0['top_bottom_mean']} -> final: {s1['left_right_mean']}/{s1['top_bottom_mean']} ({out0['correction_method']})"
    dims = f"{out0['width']}x{out0['height']}"
    crop = f" crop{rec['crop_box']}" if "crop_box" in rec else ""
    ck = f", gutter-px removed: {rec.get('corner_gutter_removed_px')}" if "corner_gutter_removed_px" in rec else ""
    rows.append([cat_of(pid), pid, f"public/kids/assets/math-quest/{out_rel}", fmt, dims, (ops + crop + (" " + extra if extra else "") + ck)[:200]])

rows.sort(key=lambda r: (r[0], r[1]))
line_tpl = "| {category} | `{id}` | `{file}` | {fmt} | {dims} | {ops} |"
md_rows = "\n".join(line_tpl.format(category=c, id=i, file=f, fmt=fm, dims=d, ops=o.replace("|", "\\|")) for c, i, f, fm, d, o in rows)

report = f"""# Math Quest asset pipeline — processing report

Generated by `Math-Quest-Assets/pipeline/` (numpy + Pillow 13). Rerunnable end-to-end:

```
python pipeline/run_prepare.py      # decode originals -> production assets + metrics
python pipeline/run_manifest.py     # manifest.json + validation
python pipeline/run_debug_sheets.py # visual QA contact sheets (debug only)
python pipeline/run_edge_check.py   # edge zoom inspection sheet (debug only)
```

Originals in `source-prompts/` are only ever opened read-only; no file in
`source-prompts/` was created, modified, renamed or deleted.

## Results summary

- Production files written: **36** (+ `manifest.json`)
- Validation: **{validation['checked']} entries checked, problems: {len(validation['problems'])}**
- Categories: characters 5, backgrounds 5, props 7, terrain 3, rewards 3,
  effects 1, decorations 7, icons 1, thumbnails 4.

## Per-asset processing

| Category | ID | Output | Format | Dimensions | Operations / QA |
|---|---|---|---|---|---|
{md_rows}
"""

# exceptions / notes
water = []
gt = metrics["mq-path-tile"]["outputs"][0]
