/**
 * scripts/vendor-fonts.mjs
 *
 * Vendor the web fonts locally.
 *
 * The application used to load Inter (and the Kids games used Baloo 2 +
 * Nunito) from fonts.googleapis.com. That is the LAST remote dependency in
 * the request path: every other library is already vendored, so the app
 * works offline — but the fonts were fetched from Google's CDN on every cold
 * load, which means:
 *
 *   • a classroom on a school network without internet waited for the font
 *   • the offline package was not completely offline
 *   • the Content-Security-Policy had to allow two remote origins
 *
 * This script downloads the font files once, on a machine WITH internet, and
 * rewrites the stylesheets to point at the local copies. After it runs, the
 * application fetches nothing from the internet for its interface.
 *
 *   node scripts/vendor-fonts.mjs
 *
 * It is idempotent: re-running it refreshes the files and leaves the
 * repository in the same shape.
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const FONT_DIR = path.join(ROOT, 'public', 'fonts');

// A modern browser User-Agent, so Google serves the woff2 files and the
// unicode-range subsets rather than the legacy ttf.
const UA =
	'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36';

const FAMILIES = [
	{
		name: 'inter',
		css: 'inter.css',
		query: 'family=Inter:wght@400;500;600;700;800&display=swap',
	},
	{
		name: 'kids',
		css: 'kids.css',
		query:
			'family=Baloo+2:wght@400;500;600;700;800&family=Nunito:wght@400;600;700;800;900&display=swap',
	},
];

async function fetchText(url) {
	const response = await fetch(url, { headers: { 'User-Agent': UA } });
	if (!response.ok) {
		throw new Error(`${url} → ${response.status} ${response.statusText}`);
	}
	return response.text();
}

async function download(url, target) {
	const response = await fetch(url, { headers: { 'User-Agent': UA } });
	if (!response.ok) {
		throw new Error(`${url} → ${response.status} ${response.statusText}`);
	}
	const buffer = Buffer.from(await response.arrayBuffer());
	fs.mkdirSync(path.dirname(target), { recursive: true });
	fs.writeFileSync(target, buffer);
	return buffer.length;
}

/**
 * Download a family's CSS and every font file it references, rewriting the
 * URLs to the local copies.
 */
async function vendorFamily(family) {
	const source = `https://fonts.googleapis.com/css2?${family.query}`;
	const css = await fetchText(source);

	const dir = path.join(FONT_DIR, family.name);
	fs.mkdirSync(dir, { recursive: true });

	// Every distinct font file the stylesheet references.
	const urls = [...new Set([...css.matchAll(/url\((https:\/\/fonts\.gstatic\.com\/[^)]+)\)/g)].map((m) => m[1]))];

	let bytes = 0;
	for (const url of urls) {
		const file = url.split('/').pop();
		const target = path.join(dir, file);
		if (fs.existsSync(target) && fs.statSync(target).size > 0) {
			bytes += fs.statSync(target).size;
			continue;
		}
		bytes += await download(url, target);
	}

	// Point every reference at the local copy. The path is absolute, so the
	// stylesheet works from any directory it is loaded into.
	const local = css.replace(
		/url\(https:\/\/fonts\.gstatic\.com\/[^)]+\/([^/)]+)\)/g,
		`url(/fonts/${family.name}/$1)`,
	);

	const header = [
		'/*',
		' * Vendored web font — generated by scripts/vendor-fonts.mjs.',
		' *',
		' * The font files in this folder are served from the application itself,',
		' * so the interface needs no internet access to render. Do not edit this',
		' * file by hand; re-run the script to refresh it.',
		' */',
		'',
	].join('\n');

	fs.writeFileSync(path.join(FONT_DIR, family.css), `${header}${local}`);
	console.log(
		`${family.name}: ${urls.length} font file(s), ${(bytes / 1024).toFixed(0)} KB → public/fonts/${family.css}`,
	);
	return urls.length;
}

let total = 0;
for (const family of FAMILIES) {
	total += await vendorFamily(family);
}
console.log(`\nDone — ${total} font files vendored under public/fonts/`);
console.log('The application now loads its interface with no internet access.');
